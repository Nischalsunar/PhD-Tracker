import {test,expect} from '@playwright/test';
test('professor, communication, follow-up and application workflow',async({page})=>{
 await page.goto('/');
 await expect(page.getByText('DEMO WORKSPACE')).toBeVisible();
 await page.getByRole('button',{name:'+ Add professor',exact:true}).click();
 await page.getByLabel('Name / title').fill('Dr. Browser Example');
 await page.getByLabel('University',{exact:true}).fill('Fictional University');
 await page.getByRole('button',{name:'Save record'}).click();
 await page.getByRole('button',{name:'Professors',exact:true}).click();
 await page.getByRole('button',{name:'Dr. Browser Example',exact:true}).click();
 await page.getByRole('button',{name:'Log communication'}).click();
 await page.getByLabel('Short summary').fill('Fictional outreach');
 await page.getByLabel('Direction').selectOption('outbound');
 await page.getByLabel('Channel').selectOption('Email');
 await page.getByRole('button',{name:'Save record'}).click();
 await page.getByRole('button',{name:'Follow-ups',exact:true}).click();
 await page.getByRole('button',{name:'+ Add task'}).click();
 await page.getByLabel('Name / title').fill('Review lab publications');
 await page.getByLabel('Due date').fill('2026-01-01');
 await page.getByRole('button',{name:'Save record'}).click();
 await page.getByRole('button',{name:'Applications',exact:true}).click();
 await page.getByRole('button',{name:'+ Add application'}).click();
 await page.getByLabel('Name / title').fill('Example PhD');
 await page.getByLabel('Dr. Browser Example').check();
 await page.getByLabel('CV',{exact:true}).selectOption('Completed');
 await page.getByRole('button',{name:'Save record'}).click();
 await expect(page.getByText('TBD / Unverified')).toBeVisible();
 await page.reload();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await expect(page.getByText('Review lab publications')).toBeVisible();
 await expect(page.getByText('Fictional outreach')).toBeVisible();
});
